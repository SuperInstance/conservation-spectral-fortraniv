C     ================================================================
C     CONSERVATION SPECTRAL SDK - FORTRAN IV (1960S STYLE)
C     MAIN DRIVER PROGRAM
C     ================================================================
C
      PROGRAM SPMAIN
      REAL LPLC
      DIMENSION TRANS(50,50), LPLC(50,50)
      DIMENSION EVALS(50), EVECS(50,50)
      DIMENSION ATTR(50), RATIOS(50)
      DIMENSION FPRINT(50)
      DIMENSION FIEDL(50)
C
      IOUT = 6
C
      WRITE(IOUT,9000)
 9000 FORMAT(1H1,///,
     1  ' CONSERVATION SPECTRAL SDK'/
     2  ' FORTRAN IV (1960S STYLE)'//
     3  ' ========================'/)
C
C     ================================================================
C     TEST 1: 5-NODE CHORD PROGRESSION
C     ================================================================
C
      N = 5
      WRITE(IOUT,9010)
 9010 FORMAT(1H0,'--- TEST: CHORD PROGRESSION ---'/)
C
      DO 100 I=1,N
      DO 100 J=1,N
      TRANS(J,I) = 0.0
  100 CONTINUE
C
C     CHORD PROGRESSION TRANSITIONS
C     NODE 1=C(TONIC) 2=AM(REL MINOR) 3=F(SUBDOM) 4=G(DOM) 5=C'(OCT)
C
      TRANS(2,1) = 0.3
      TRANS(3,1) = 0.2
      TRANS(4,1) = 0.5
      TRANS(3,2) = 0.4
      TRANS(4,2) = 0.1
      TRANS(5,2) = 0.5
      TRANS(4,3) = 0.6
      TRANS(1,3) = 0.4
      TRANS(1,4) = 0.3
      TRANS(5,4) = 0.7
      TRANS(1,5) = 0.5
      TRANS(2,5) = 0.3
      TRANS(3,5) = 0.2
C
C     SYMMETRIZE
C
      DO 110 I=1,N
      DO 110 J=1,N
      IF (I-J) 111,110,111
  111 CONTINUE
      AVG = (TRANS(J,I) + TRANS(I,J)) / 2.0
      TRANS(J,I) = AVG
      TRANS(I,J) = AVG
  110 CONTINUE
C
      WRITE(IOUT,9020)
 9020 FORMAT(1H0,'TRANSITION MATRIX'/)
      DO 120 I=1,N
      WRITE(IOUT,9030) (TRANS(J,I),J=1,N)
  120 CONTINUE
 9030 FORMAT(5F10.4)
C
C     BUILD LAPLACIAN
C
      CALL SPLAPL(TRANS,N,LPLC)
C
      WRITE(IOUT,9040)
 9040 FORMAT(1H0,'LAPLACIAN MATRIX'/)
      DO 130 I=1,N
      WRITE(IOUT,9030) (LPLC(J,I),J=1,N)
  130 CONTINUE
C
C     EIGENDECOMPOSITION
C
      MAXIT = 100
      CALL SPJACB(LPLC,N,EVALS,EVECS,MAXIT,IERR)
C
      IF (IERR) 140,150,140
  140 WRITE(IOUT,9050)
 9050 FORMAT(1H0,'*** EIGEN: NO CONVERGENCE ***')
      GOTO 999
C
  150 CONTINUE
      WRITE(IOUT,9060)
 9060 FORMAT(1H0,'EIGENVALUES'/)
      WRITE(IOUT,9030) (EVALS(I),I=1,N)
C
      WRITE(IOUT,9070)
 9070 FORMAT(1H0,'EIGENVECTORS'/)
      DO 160 I=1,N
      WRITE(IOUT,9030) (EVECS(I,J),J=1,N)
  160 CONTINUE
C
C     CONSERVATION RATIOS
C
      ATTR(1) = 1.0
      ATTR(2) = 6.0
      ATTR(3) = 4.0
      ATTR(4) = 5.0
      ATTR(5) = 8.0
C
      WRITE(IOUT,9080)
 9080 FORMAT(1H0,'CONSERVATION RATIOS'/)
      DO 170 IEV=1,N
      CALL SPCONS(EVECS,ATTR,N,IEV,RATIOS(IEV))
      WRITE(IOUT,9090) IEV, EVALS(IEV), RATIOS(IEV)
  170 CONTINUE
 9090 FORMAT(1H ,' EV ',I2,5X,'EIGVAL = ',F10.6,5X,'RATIO = ',F10.6)
C
C     SPECTRAL GAP
C
      CALL SPSGAP(EVALS,N,SGAP)
      WRITE(IOUT,9100) SGAP
 9100 FORMAT(1H0,'SPECTRAL GAP = ',F12.6)
C
C     CHEEGER CONSTANT (FIEDLER = EIGENVECTOR 2)
C
      DO 180 I=1,N
      FIEDL(I) = EVECS(I,2)
  180 CONTINUE
C
      CALL SPLAPL(TRANS,N,LPLC)
      CALL SPCHKR(LPLC,FIEDL,N,CHEEG)
      WRITE(IOUT,9110) CHEEG
 9110 FORMAT(1H0,'CHEEGER CONSTANT = ',F12.6)
C
C     SPECTRAL FINGERPRINT
C
      CALL SPFING(EVALS,N,FPRINT,FLEN)
      WRITE(IOUT,9120)
 9120 FORMAT(1H0,'SPECTRAL FINGERPRINT'/)
      WRITE(IOUT,9035) (FPRINT(I),I=1,N)
 9035 FORMAT(5E12.4)
C
C
C     ANOMALY DETECTION TEST
C
      WRITE(IOUT,9130)
 9130 FORMAT(1H0,'ANOMALY DETECTION'/
     1       1H ,'FEEDING EIGENVALUES AS OBSERVATIONS'/)
C
      CALL SPANMI(5.0)
C
C     FILL WINDOW WITH FIRST EIGENVALUE (ESTABLISH BASELINE)
C
      DO 201 ITR=1,6
      DO 210 I=1,N
      CALL SPANOM(EVALS(I),ISTAT)
      IF (ISTAT) 215,210,215
  215 WRITE(IOUT,9140) EVALS(I), ISTAT
  210 CONTINUE
  201 CONTINUE
C
      WRITE(IOUT,9150)
 9150 FORMAT(1H0,'FEEDING ANOMALY VALUE 999.0'/)
      CALL SPANOM(999.0,ISTAT)
      WRITE(IOUT,9140) 999.0, ISTAT
 9140 FORMAT(1H ,'OBS = ',F10.3,5X,'STATUS = ',I2)
C
C     SUMMARY
C
      WRITE(IOUT,9200)
 9200 FORMAT(1H1,//
     1  ' ========================'/
     2  ' ANALYSIS SUMMARY'/
     3  ' ========================'//)
C
      WRITE(IOUT,9210) N
 9210 FORMAT(1H ,'NODES      = ',I2)
      WRITE(IOUT,9220) EVALS(1), EVALS(2)
 9220 FORMAT(1H ,'LAMBDA_1   = ',F12.6/
     1       1H ,'LAMBDA_2   = ',F12.6)
      WRITE(IOUT,9230) SGAP
 9230 FORMAT(1H ,'SPEC GAP   = ',F12.6)
      WRITE(IOUT,9240) CHEEG
 9240 FORMAT(1H ,'CHEEGER    = ',F12.6)
      WRITE(IOUT,9250)
 9250 FORMAT(1H0,'=== ANALYSIS COMPLETE ==='//)
C
  999 CONTINUE
      STOP
      END
